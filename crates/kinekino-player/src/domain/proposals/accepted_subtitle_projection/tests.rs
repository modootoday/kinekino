use super::*;
use crate::domain::proposals::{
    Card, Correction, CueSourceSnapshot, DocumentCorrection, DocumentSourceSnapshot, DraftState,
    GeneratedResult, Highlight, ProposalDocument, proposal_document_version,
};

fn source() -> SourceSnapshot {
    SourceSnapshot::Cue(CueSourceSnapshot {
        source_id: "source-1".into(),
        source_revision: DecimalU64(7),
        source_sha256: "a".repeat(64),
        // Deliberately not time-sorted, with sub-millisecond values. Projection
        // must preserve source order/precision rather than invent an export policy.
        cues: vec![
            SourceCue {
                cue_id: "cue-b".into(),
                text: "Keep 원문.".into(),
                start_us: Some(DecimalU64(2001)),
                end_us: Some(DecimalU64(3999)),
            },
            SourceCue {
                cue_id: "cue-a".into(),
                text: "old text".into(),
                start_us: Some(DecimalU64(1)),
                end_us: Some(DecimalU64(999)),
            },
        ],
    })
}
fn correction() -> ProposalPayload {
    ProposalPayload::Correction {
        edits: vec![Correction {
            cue_id: "cue-a".into(),
            text: "수정 text".into(),
        }],
    }
}
fn fixture(source: SourceSnapshot, output: ProposalPayload) -> StoredProposal {
    let receipt = AcceptanceReceipt {
        proposal_id: "proposal-1".into(),
        draft_revision: DecimalU64(1),
        output_revision: DecimalU64(2),
        source_id: source.source_id().into(),
        source_revision: source.source_revision(),
        source_sha256: source.source_sha256().into(),
        output: output.clone(),
        automatic_application_enabled: false,
    };
    let state = StoredProposal {
        document: ProposalDocument {
            schema_version: proposal_document_version(&source, None).into(),
            proposal_id: "proposal-1".into(),
            source,
            generated: GeneratedResult {
                task: output.task(),
                raw_text: "original generated bytes, not a new model result".into(),
            },
            draft_revision: DecimalU64(2),
            state: DraftState::Editable,
            draft: Some(output),
            import_error: None,
        },
        acceptance: Some(receipt),
        historical: None,
    };
    state.validate().unwrap();
    state
}

#[test]
fn preserves_source_order_unedited_text_exact_time_and_original_buffers() {
    let state = fixture(source(), correction());
    let before = serde_json::to_vec(&state).unwrap();
    let receipt = state.acceptance.as_ref().unwrap();
    let projected = project(&state, receipt).unwrap();
    assert!(std::ptr::eq(projected.acceptance(), receipt));
    let cues = projected.cues();
    assert_eq!(cues.len(), 2);
    assert_eq!(cues[0].source().cue_id, "cue-b");
    assert_eq!(cues[0].text(), "Keep 원문.");
    assert_eq!((cues[0].in_us().0, cues[0].out_us().0), (2001, 3999));
    assert_eq!(cues[1].source().cue_id, "cue-a");
    assert_eq!(cues[1].text(), "수정 text");
    assert_eq!((cues[1].in_us().0, cues[1].out_us().0), (1, 999));
    assert_eq!(cues[1].source().text, "old text");
    assert_eq!(serde_json::to_vec(&state).unwrap(), before);
}

#[test]
fn requires_explicit_acceptance_without_mutating_or_auto_accepting() {
    let mut state = fixture(source(), correction());
    let expected = state.acceptance.take().unwrap();
    let before = serde_json::to_vec(&state).unwrap();
    assert_eq!(
        project(&state, &expected).unwrap_err(),
        ProjectionError::NotAccepted
    );
    assert_eq!(serde_json::to_vec(&state).unwrap(), before);
}

#[test]
fn rejects_changed_receipt_identity_or_output_without_store_cas() {
    let state = fixture(source(), correction());
    let receipt = state.acceptance.as_ref().unwrap();
    let mut changed = receipt.clone();
    changed.output_revision = DecimalU64(3);
    assert_eq!(
        project(&state, &changed).unwrap_err(),
        ProjectionError::AcceptanceMismatch
    );
    let mut changed = receipt.clone();
    changed.source_sha256 = "b".repeat(64);
    assert_eq!(
        project(&state, &changed).unwrap_err(),
        ProjectionError::AcceptanceMismatch
    );
    let mut changed = receipt.clone();
    let ProposalPayload::Correction { edits } = &mut changed.output else {
        unreachable!()
    };
    edits[0].text = "different accepted expectation".into();
    assert_eq!(
        project(&state, &changed).unwrap_err(),
        ProjectionError::AcceptanceMismatch
    );
}

#[test]
fn rejects_card_and_highlight_payloads_as_unsupported_tasks() {
    for output in [
        ProposalPayload::Cards {
            cards: vec![Card {
                front: "front".into(),
                back: "back".into(),
                source_refs: vec!["cue-a".into()],
            }],
        },
        ProposalPayload::Highlights {
            highlights: vec![Highlight {
                title: "title".into(),
                source_refs: vec!["cue-a".into()],
            }],
        },
    ] {
        let state = fixture(source(), output);
        assert_eq!(
            project(&state, state.acceptance.as_ref().unwrap()).unwrap_err(),
            ProjectionError::UnsupportedTask
        );
    }
}

#[test]
fn rejects_document_correction_without_inventing_cues_or_timestamps() {
    use sha2::{Digest, Sha256};
    let asset = serde_json::to_string(&serde_json::json!({"messages":[{"role":"user","content":concat!(
        "Edit this ASR draft. Correct punctuation only. Do not guess unclear words. JSON only: {\"proposed\":string,\"uncertain_words\":[string]}. Under100words. /no_think\n",
        r#"["Original document."]"#)}]})).unwrap();
    let hash = format!("{:x}", Sha256::digest(asset.as_bytes()));
    let document =
        DocumentSourceSnapshot::from_asset("document-1".into(), DecimalU64(7), hash, asset)
            .unwrap();
    let output = ProposalPayload::DocumentCorrection {
        edits: vec![DocumentCorrection {
            source_ref: document.text_reference("/0").unwrap(),
            text: "Corrected document.".into(),
        }],
    };
    let state = fixture(SourceSnapshot::Document(document), output);
    assert_eq!(
        project(&state, state.acceptance.as_ref().unwrap()).unwrap_err(),
        ProjectionError::UnsupportedSource
    );
}

#[test]
fn missing_timing_stays_unknown_and_invalid_pairs_use_existing_validation() {
    let mut state = fixture(source(), correction());
    let SourceSnapshot::Cue(source) = &mut state.document.source else {
        unreachable!()
    };
    source.cues[0].start_us = None;
    source.cues[0].end_us = None;
    assert_eq!(
        project(&state, state.acceptance.as_ref().unwrap()).unwrap_err(),
        ProjectionError::MissingCueTiming { cue_index: 0 }
    );
    let SourceSnapshot::Cue(source) = &mut state.document.source else {
        unreachable!()
    };
    source.cues[0].start_us = Some(DecimalU64(4));
    source.cues[0].end_us = Some(DecimalU64(4));
    assert!(matches!(
        project(&state, state.acceptance.as_ref().unwrap()),
        Err(ProjectionError::InvalidState(_))
    ));
}
